"""Evaluation report generation (WBS 7.16).

Merges two judge files, computes agreement, runs tiebreak where needed,
and generates a final evaluation report (Markdown + JSON).

Usage:
  python -m eval.report --results eval/results/ \
    --judge1 eval/results/judge_alice.json \
    --judge2 eval/results/judge_bob.json \
    --output eval/results/final_report.md
"""

from __future__ import annotations

import json
from pathlib import Path

import click


@click.command()
@click.option("--results", required=True, type=click.Path(exists=True))
@click.option("--judge1", required=True, type=click.Path(exists=True))
@click.option("--judge2", required=True, type=click.Path(exists=True))
@click.option("--output", required=True)
@click.option("--tiebreak-threshold", default=0.5, type=float,
              help="|j1_a - j2_a| threshold to flag as tiebreak needed (default 0.5).")
def main(results: str, judge1: str, judge2: str, output: str, tiebreak_threshold: float) -> None:
    """Generate final evaluation report from two judge files."""
    j1 = json.loads(Path(judge1).read_text(encoding="utf-8"))
    j2 = json.loads(Path(judge2).read_text(encoding="utf-8"))
    summary = json.loads((Path(results) / "summary.json").read_text(encoding="utf-8"))

    cases = sorted(set(j1.keys()) | set(j2.keys()))
    rows: list[dict] = []
    tiebreaks: list[str] = []

    for cid in cases:
        r1 = j1.get(cid, {})
        r2 = j2.get(cid, {})
        a1 = r1.get("a_score", None)
        a2 = r2.get("a_score", None)

        if a1 is None or a2 is None:
            avg_a = a1 if a1 is not None else a2
            needs_tiebreak = False
        else:
            avg_a = (a1 + a2) / 2
            needs_tiebreak = abs(a1 - a2) >= tiebreak_threshold

        if needs_tiebreak:
            tiebreaks.append(cid)

        r1_score = r1.get("r_score")
        r2_score = r2.get("r_score")
        avg_r = (r1_score + r2_score) / 2 if r1_score and r2_score else (r1_score or r2_score)

        rows.append({
            "case_id": cid,
            "a_j1": a1,
            "a_j2": a2,
            "a_avg": avg_a,
            "r_avg": avg_r,
            "needs_tiebreak": needs_tiebreak,
        })

    a_scores = [r["a_avg"] for r in rows if r["a_avg"] is not None]
    r_scores = [r["r_avg"] for r in rows if r["r_avg"] is not None]

    final = {
        "total_cases": len(rows),
        "judged_by_both": sum(1 for r in rows if r["a_j1"] is not None and r["a_j2"] is not None),
        "tiebreak_needed": len(tiebreaks),
        "tiebreak_cases": tiebreaks,
        "avg_a_score": round(sum(a_scores) / max(len(a_scores), 1), 3),
        "avg_r_score": round(sum(r_scores) / max(len(r_scores), 1), 2),
        "recall_at_10": summary.get("avg_recall_at_10"),
        "traceability": summary.get("avg_traceability"),
        "rows": rows,
    }

    md = _render_report_md(final)
    out = Path(output)
    out.write_text(md, encoding="utf-8")
    (out.with_suffix(".json")).write_text(json.dumps(final, indent=2), encoding="utf-8")
    click.echo(f"Report written: {out}")
    if tiebreaks:
        click.echo(f"⚠ Tiebreak needed for {len(tiebreaks)} cases: {tiebreaks}")


def _render_report_md(r: dict) -> str:
    lines = [
        "# Evaluation Report — Linux-Diag-Agent",
        "",
        f"**Total cases:** {r['total_cases']}  ",
        f"**Judged by both:** {r['judged_by_both']}  ",
        f"**Tiebreaks needed:** {r['tiebreak_needed']}  ",
        "",
        "## Metrics",
        "",
        f"| Metric | Value |",
        f"|--------|-------|",
        f"| Root-cause correct (avg A) | {r['avg_a_score']:.0%} |",
        f"| Report readability (avg R) | {r['avg_r_score']:.1f}/10 |",
        f"| Recall@10 (retrieval) | {r.get('recall_at_10', 'N/A')} |",
        f"| Claim traceability | {r.get('traceability', 'N/A')} |",
        "",
        "## Per-Case Results",
        "",
        "| Case | A-j1 | A-j2 | A-avg | R-avg | Tiebreak |",
        "|------|------|------|-------|-------|----------|",
    ]
    for row in r["rows"]:
        tb = "⚠ YES" if row["needs_tiebreak"] else ""
        lines.append(
            f"| {row['case_id']} | {row['a_j1']} | {row['a_j2']} "
            f"| {row['a_avg']} | {row['r_avg']} | {tb} |"
        )
    lines += ["", "---", "_Generated by Linux-Diag-Agent eval framework_"]
    return "\n".join(lines)


if __name__ == "__main__":
    main()
