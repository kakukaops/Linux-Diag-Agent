def _S(lang: str) -> dict[str, Any]:
    return _STR["zh"] if (lang or "en").lower() == "zh" else _STR["en"]


def render_md(state: dict[str, Any], lang: str = "en") -> str:
    """Render a Markdown diagnosis report from agent state.

    ``lang`` ∈ {'en', 'zh'} — picks the section headers and banner phrases
    from _STR. Data values (commit hashes, function names, tool names,
    user-supplied text, LLM output) are NEVER translated.
    """
    react_verdict = state.get("react_verdict", "diagnosed")

    # ── Insufficient evidence branch (ADR-024 / T-010) ────────────────────────
    if react_verdict != "diagnosed":
        return _render_insufficient_md(state, lang=lang)

    S = _S(lang)
    unknown = S["unknown_value"]
    fault_kind = state.get("fault_kind") or unknown
    fault_summary = state.get("fault_summary", "")
    olk_tag = state.get("olk_version_tag") or unknown
    hostname = state.get("hostname") or unknown
    final_analysis = state.get("final_analysis", "") or state.get("react_final_answer", "")
    # Backward-compat: if state was built by old bind_claims (or by test
    # fixtures using `claims` only), derive the split from the `verified`
    # flag so old callers still render correctly.
    verified_claims = state.get("verified_claims")
    speculative_claims = state.get("speculative_claims")
    if verified_claims is None or speculative_claims is None:
        legacy = state.get("claims", []) or []
        verified_claims = [c for c in legacy if c.get("verified")]
        speculative_claims = [c for c in legacy if not c.get("verified")]
    groundedness = state.get("groundedness")
    if groundedness is None:
        if not verified_claims and not speculative_claims:
            groundedness = "speculative"
        elif verified_claims and len(verified_claims) >= len(speculative_claims):
            groundedness = "grounded"
        else:
            groundedness = "speculative"
    evidence = state.get("evidence", [])
    tool_trace = state.get("react_tool_trace", [])
    iterations = state.get("react_iterations", 0)
    tokens_used = state.get("react_tokens_used", 0)
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    groundedness_banner = {
        "grounded":    S["banner_grounded"],
        "speculative": S["banner_speculative"],
        "n/a":         S["banner_na"],
    }.get(groundedness, "")

    lines: list[str] = [
        f"# {S['title']}",
        "",
        f"**{S['k_generated']}:** {timestamp}  ",
        f"**{S['k_host']}:** {hostname}  ",
        f"**{S['k_kernel']}:** {olk_tag}  ",
        f"**{S['k_fault_type']}:** `{fault_kind}`  ",
        f"**{S['k_investigation']}:** {iterations} {S['u_iter']} · "
        f"{tokens_used:,} {S['u_tokens']}  ",
        groundedness_banner + "  ",
        "",
        S["h_executive"],
        "",
        fault_summary or S["msg_no_summary"],
        "",
        S["h_root_cause"],
        "",
        final_analysis or S["msg_no_analysis"],
        "",
    ]

    if verified_claims:
        lines += [S["h_verified"], ""]
        for c in verified_claims:
            refs = ", ".join(c.get("evidence_refs", []))
            strength = c.get("evidence_strength", 0.0)
            lines.append(
                f"- {c.get('text','')} "
                f"_({S['k_refs']}: {refs}; {S['k_overlap']}: {strength:.2f})_"
            )
        lines.append("")

    if speculative_claims:
        lines += [
            S["h_speculation"],
            "",
            S["msg_speculation_intro"],
            "",
        ]
        for c in speculative_claims:
            refs = ", ".join(c.get("evidence_refs", []))
            strength = c.get("evidence_strength", 0.0)
            reason = (S["reason_no_evidence"]
                      if not refs or strength == 0.0
                      else S["reason_low_overlap"].format(strength=strength))
            lines.append(
                f"- {c.get('text','')} _({S['k_refs']}: {refs or 'none'}; {reason})_"
            )
        lines.append("")

    if evidence:
        lines += [
            S["h_evidence"],
            "",
            S["tbl_evidence_header"],
            S["tbl_evidence_sep"],
        ]
        for i, ev in enumerate(evidence[:10], 1):
            title = ev.get("title", "")[:60]
            lines.append(
                f"| {i} | {ev.get('route','')} | {title} | {ev.get('score',0):.3f} |"
            )
        lines.append("")

    if tool_trace:
        lines += [S["h_tool_trace"], ""]
        for entry in tool_trace:
            status = "✗" if entry.get("error") else "✓"
            lines.append(
                f"- [{status}] {S['step_word']} {entry['step']} "
                f"`{entry['tool']}` args={entry['args']}"
            )
        lines.append("")

    lines += ["---", S["footer"]]
    return "\n".join(lines)


def _render_insufficient_md(state: dict[str, Any], lang: str = "en") -> str:
    """Render an insufficient-evidence report with next-step guidance (T-010)."""
    S = _S(lang)
    unknown = S["unknown_value"]
    react_verdict = state.get("react_verdict", "insufficient_evidence")
    final_answer = state.get("react_final_answer", "")
    fault_kind = state.get("fault_kind") or unknown
    olk_tag = state.get("olk_version_tag") or unknown
    hostname = state.get("hostname") or unknown
    iterations = state.get("react_iterations", 0)
    tokens_used = state.get("react_tokens_used", 0)
    tool_trace = state.get("react_tool_trace", [])
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    verdict_label = S["verdicts"].get(react_verdict, react_verdict)

    lines = [
        f"# {S['title_incomplete']}",
        "",
        f"**{S['k_generated']}:** {timestamp}  ",
        f"**{S['k_host']}:** {hostname}  ",
        f"**{S['k_kernel']}:** {olk_tag}  ",
        f"**{S['k_fault_type']}:** `{fault_kind}`  ",
        f"**{S['k_outcome']}:** {verdict_label} ({iterations} {S['u_iter']} · "
        f"{tokens_used:,} {S['u_tokens']})  ",
        "",
        S["h_status"],
        "",
        S["msg_status"].format(verdict=verdict_label),
        "",
    ]

    if final_answer:
        lines += [
            S["h_additional_info"],
            "",
            final_answer,
            "",
        ]
    else:
        lines += [
            S["h_suggested"],
            "",
            *S["next_steps"],
            "",
        ]

    if tool_trace:
        lines += [S["h_tools_called"], ""]
        for entry in tool_trace:
            status = "✗" if entry.get("error") else "✓"
            lines.append(
                f"- [{status}] {S['step_word']} {entry['step']} `{entry['tool']}`"
            )
        lines.append("")

    lines += ["---", S["footer"]]
    return "\n".join(lines)


def render_json(state: dict[str, Any]) -> dict[str, Any]:
    """Return a structured JSON report dict (schema_version 2).

    JSON output is intentionally NOT translated — keys and label values
    are stable English identifiers for API consumers. UI / CLI rendering
    of these values can localize at presentation time.
    """
    react_verdict = state.get("react_verdict", "diagnosed")
    tool_trace = state.get("react_tool_trace", [])

    base: dict[str, Any] = {
        "schema_version": _SCHEMA_VERSION,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "system": {
            "hostname": state.get("hostname"),
            "olk_version_tag": state.get("olk_version_tag"),
            "kernel_version": state.get("kernel_version"),
        },
        "fault": {
            "kind": state.get("fault_kind"),
            "summary": state.get("fault_summary"),
            "diagnostic_route": state.get("diagnostic_route"),
        },
        "react": {
            "verdict": react_verdict,
            "iterations": state.get("react_iterations", 0),
            "tokens_used": state.get("react_tokens_used", 0),
            "tool_calls": [
                {
                    "step": t.get("step"),
                    "tool": t.get("tool"),
                    "args": t.get("args"),
                    "error": t.get("error", False),
                }
                for t in tool_trace
            ],
        },
    }

    if react_verdict == "diagnosed":
        base["analysis"] = {
            "final": state.get("final_analysis") or state.get("react_final_answer"),
        }
        base["claims"] = state.get("claims", [])
        base["verified_claims"] = state.get("verified_claims", [])
        base["speculative_claims"] = state.get("speculative_claims", [])
        base["groundedness"] = state.get("groundedness", "speculative")
        base["evidence_count"] = len(state.get("evidence", []))
        base["top_evidence"] = [
            {
                "route": e.get("route"),
                "title": e.get("title"),
                "score": e.get("score"),
                "commit_hash": e.get("commit_hash"),
                "bug_id": e.get("bug_id"),
                "cve_id": e.get("cve_id"),
            }
            for e in state.get("evidence", [])[:10]
        ]
    else:
        base["insufficient_evidence"] = {
            "reason": react_verdict,
            "agent_message": state.get("react_final_answer", ""),
        }

    return base
