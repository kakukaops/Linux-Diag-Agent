"""Report renderer — Markdown + JSON schema output (WBS 7.10)."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any


def render_md(state: dict[str, Any]) -> str:
    """Render a Markdown diagnosis report from DiagnosisState."""
    fault_kind = state.get("fault_kind", "unknown")
    fault_summary = state.get("fault_summary", "")
    olk_tag = state.get("olk_version_tag", "unknown")
    hostname = state.get("hostname") or "unknown"
    final_analysis = state.get("final_analysis", "")
    hypotheses = state.get("hypotheses", [])
    claims = state.get("claims", [])
    evidence = state.get("evidence", [])
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines: list[str] = [
        f"# Linux Kernel Fault Diagnosis Report",
        f"",
        f"**Generated:** {timestamp}  ",
        f"**Host:** {hostname}  ",
        f"**Kernel:** {olk_tag}  ",
        f"**Fault type:** `{fault_kind}`  ",
        f"",
        f"## Executive Summary",
        f"",
        fault_summary,
        f"",
        f"## Root Cause Analysis",
        f"",
        final_analysis or "_Analysis not available._",
        f"",
    ]

    if hypotheses:
        lines += [
            "## Hypotheses",
            "",
        ]
        for h in hypotheses:
            status_icon = {"confirmed": "✓", "rejected": "✗", "uncertain": "?", "pending": "·"}.get(
                h.get("status", "pending"), "·"
            )
            lines.append(
                f"- [{status_icon}] **{h.get('id','')}** (confidence={h.get('confidence',0):.0%}): "
                f"{h.get('text','')}"
            )
        lines.append("")

    if claims:
        lines += [
            "## Supporting Claims",
            "",
        ]
        for c in claims:
            verified = "✓" if c.get("verified") else "?"
            refs = ", ".join(c.get("evidence_refs", []))
            lines.append(f"- [{verified}] {c.get('text','')} _(refs: {refs or 'none'})_")
        lines.append("")

    if evidence:
        lines += [
            "## Evidence",
            "",
            "| # | Route | Title | Score |",
            "|---|-------|-------|-------|",
        ]
        for i, ev in enumerate(evidence[:10], 1):
            title = ev.get("title", "")[:60]
            lines.append(
                f"| {i} | {ev.get('route','')} | {title} | {ev.get('score',0):.3f} |"
            )
        lines.append("")

    lines += [
        "---",
        "_Report generated by Linux-Diag-Agent_",
    ]
    return "\n".join(lines)


def render_json(state: dict[str, Any]) -> dict[str, Any]:
    """Return a structured JSON report dict."""
    return {
        "schema_version": 1,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "system": {
            "hostname": state.get("hostname"),
            "olk_version_tag": state.get("olk_version_tag"),
            "kernel_version": state.get("kernel_version"),
        },
        "fault": {
            "kind": state.get("fault_kind"),
            "summary": state.get("fault_summary"),
            "sop": state.get("sop_name"),
        },
        "analysis": {
            "final": state.get("final_analysis"),
            "candidates": state.get("candidate_analyses", []),
        },
        "hypotheses": state.get("hypotheses", []),
        "claims": state.get("claims", []),
        "evidence_count": len(state.get("evidence", [])),
        "top_evidence": [
            {
                "route": e.get("route"),
                "title": e.get("title"),
                "score": e.get("score"),
                "commit_hash": e.get("commit_hash"),
                "bug_id": e.get("bug_id"),
                "cve_id": e.get("cve_id"),
            }
            for e in state.get("evidence", [])[:10]
        ],
    }
